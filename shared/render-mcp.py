#!/usr/bin/env python3
"""Render shared/mcp.json into each agent's MCP config.

  shared/render-mcp.py          rewrite the generated outputs
  shared/render-mcp.py --check  exit 1 if any output is stale (used by test/shared-sync.zsh)

Outputs:
  configs/opencode/files/opencode.jsonc  the "mcp" block between the BEGIN/END markers
  configs/claude/files/mcp.json          {"mcpServers": ...}, registered by bin/sync.sh
"""
import json, re, sys, textwrap
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "shared/mcp.json"
OPENCODE = ROOT / "configs/opencode/files/opencode.jsonc"
CLAUDE = ROOT / "configs/claude/files/mcp.json"
BEGIN = "// BEGIN generated by shared/render-mcp.py from shared/mcp.json — do not edit"
END = "// END generated"
# Claude's headersHelper; sync.sh expands $HOME at registration time.
BEARER_HELPER = "$HOME/.config/dot/claude/bin/mcp-bearer.sh"


def targets(s):
    return s.get("only", ["opencode", "claude"])


def opencode_server(s):
    if "command" in s:
        out = {"type": "local", "command": s["command"]}
        if "env" in s:
            out["environment"] = {k: "{env:%s}" % v for k, v in s["env"].items()}
    else:
        out = {"type": "remote", "url": s["url"]}
        if "bearer" in s:
            out["oauth"] = False
            out["headers"] = {"Authorization": "Bearer {env:%s}" % s["bearer"]}
    return out


def claude_server(name, s):
    if "command" in s:
        out = {"type": "stdio", "command": s["command"][0], "args": s["command"][1:]}
        if "env" in s:
            sys.exit(f"{name}: env passthrough is not supported for claude yet")
    else:
        out = {"type": "http", "url": s["url"]}
        if "bearer" in s:
            out["headersHelper"] = f"{BEARER_HELPER} {s['bearer']}"
    return out


def render_opencode(servers, indent="  "):
    lines = [BEGIN, '"mcp": {', '  "servers": {']
    entries = [(n, s) for n, s in servers.items() if "opencode" in targets(s)]
    for i, (name, s) in enumerate(entries):
        for c in textwrap.wrap(s.get("comment", ""), 72):
            lines.append(f"    // {c}")
        body = json.dumps({name: opencode_server(s)}, indent=2)[1:-1].strip("\n")
        body = ["  " + l for l in body.splitlines()]
        body[-1] += "," if i < len(entries) - 1 else ""
        lines += body
    lines += ["  }", "},", END]
    return "\n".join(indent + l for l in lines)


def main():
    check = "--check" in sys.argv[1:]
    servers = json.loads(SRC.read_text())["servers"]
    oc = OPENCODE.read_text()
    pat = re.compile(r"^([ \t]*)" + re.escape(BEGIN) + r".*?" + re.escape(END) + r"$", re.S | re.M)
    m = pat.search(oc)
    if not m:
        sys.exit(f"{OPENCODE.relative_to(ROOT)}: generated-block markers not found")
    want = {
        OPENCODE: oc[: m.start()] + render_opencode(servers, m.group(1)) + oc[m.end():],
        CLAUDE: json.dumps(
            {"mcpServers": {n: claude_server(n, s) for n, s in servers.items() if "claude" in targets(s)}},
            indent=2,
        ) + "\n",
    }
    stale = [p for p, text in want.items() if not p.exists() or p.read_text() != text]
    if check:
        for p in stale:
            print(f"stale: {p.relative_to(ROOT)} (run shared/render-mcp.py)", file=sys.stderr)
        sys.exit(1 if stale else 0)
    for p in stale:
        p.write_text(want[p])
        print(f"wrote {p.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
